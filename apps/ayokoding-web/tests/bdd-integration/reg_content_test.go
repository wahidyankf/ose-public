package bddintegration

import (
	"github.com/cucumber/godog"

	"github.com/wahidyankf/ose-public/apps/ayokoding-web/tests/internal/glue"
)

func registerContentSteps(ctx *godog.ScenarioContext, world *glue.World) {
	ctx.Given(`^a published Markdown lesson exists in the shared corpus$`, world.StepPublishedMarkdownLessonExistsSharedCorpus)
	ctx.When(`^a reader requests its route without running browser scripts$`, world.StepReaderRequestsRouteWithoutRunningBrowserScripts)
	ctx.Then(`^the response contains the lesson title and readable article body$`, world.StepResponseContainsLessonTitleReadableArticleBody)
	ctx.Step(`^the response does not depend on a Next\.js build artifact$`, world.StepResponseDoesDependNextJsBuildArtifact)
	ctx.Given(`^a section contains published pages with valid titles, slugs, and weights$`, world.StepSectionContainsPublishedPagesValidTitlesSlugsWei)
	ctx.When(`^a reader opens that section$`, world.StepReaderOpensSection)
	ctx.Then(`^page titles and links match their authored metadata$`, world.StepPageTitlesLinksMatchTheirAuthoredMetadata)
	ctx.Step(`^the pages follow the established weight and title ordering$`, world.StepPagesFollowEstablishedWeightTitleOrdering)
	ctx.Given(`^a lesson is marked as a draft$`, world.StepLessonMarkedDraft)
	ctx.Step(`^draft viewing is disabled$`, world.StepDraftViewingDisabled)
	ctx.When(`^a reader requests the lesson or searches the corpus$`, world.StepReaderRequestsLessonSearchesCorpus)
	ctx.Then(`^the lesson is absent from the public results$`, world.StepLessonAbsentFromPublicResults)
	ctx.Step(`^its direct route returns not found$`, world.StepDirectRouteReturnsFound)
	ctx.Given(`^a Markdown page has invalid required frontmatter$`, world.StepMarkdownPageHasInvalidRequiredFrontmatter)
	ctx.When(`^the content corpus is loaded$`, world.StepContentCorpusLoaded)
	ctx.Then(`^that page is excluded from the published catalog$`, world.StepPageExcludedFromPublishedCatalog)
	ctx.Step(`^the developer receives a diagnostic identifying the invalid source$`, world.StepDeveloperReceivesDiagnosticIdentifyingInvalidSou)
	ctx.Given(`^a lesson contains tables, task lists, raw details markup, and nested headings$`, world.StepLessonContainsTablesTaskListsRawDetailsMarkupNes)
	ctx.When(`^a reader opens that lesson$`, world.StepReaderOpensLesson)
	ctx.Then(`^those authored structures render with the established article styling$`, world.StepThoseAuthoredStructuresRenderEstablishedArticleS)
	ctx.Step(`^the page has one title heading with a normalized body outline$`, world.StepPageHasOneTitleHeadingNormalizedBodyOutline)
	ctx.Step(`^the table of contents links to stable body heading anchors$`, world.StepTableContentsLinksStableBodyHeadingAnchors)
	ctx.Given(`^a lesson contains a "([^"]*)" shortcode fixture$`, world.StepLessonContainsShortcodeFixture)
	ctx.When(`^a reader opens the fixture and activates its supported controls$`, world.StepReaderOpensFixtureActivatesSupportedControls)
	ctx.Then(`^the "([^"]*)" is available to the reader$`, world.StepAvailableReader)
	ctx.Given(`^a section index contains a relative Markdown link with a heading fragment$`, world.StepSectionIndexContainsRelativeMarkdownLinkHeadingF)
	ctx.When(`^a reader follows that link$`, world.StepReaderFollowsLink)
	ctx.Then(`^the destination is resolved relative to that section's directory$`, world.StepDestinationResolvedRelativeSectionSDirectory)
	ctx.Step(`^the reader reaches the intended heading in the same locale$`, world.StepReaderReachesIntendedHeadingSameLocale)
	ctx.Given(`^a lesson contains annotated fenced code$`, world.StepLessonContainsAnnotatedFencedCode)
	ctx.When(`^a reader copies that code block$`, world.StepReaderCopiesCodeBlock)
	ctx.Then(`^the clipboard contains its exact source text and newlines$`, world.StepClipboardContainsExactSourceTextNewlines)
	ctx.Step(`^the code block shows its language label and readable highlighting$`, world.StepCodeBlockShowsLanguageLabelReadableHighlighting)
	ctx.Given(`^a lesson contains a "([^"]*)" fixture$`, world.StepLessonContainsFixture)
	ctx.When(`^a reader opens the lesson$`, world.StepReaderOpensLesson2)
	ctx.Then(`^the reader sees "([^"]*)"$`, world.StepReaderSees)
	ctx.Step(`^the source notation is not presented as the rendered result$`, world.StepSourceNotationPresentedRenderedResult)
	ctx.Given(`^a lesson contains a long inline token and a wide fenced code block$`, world.StepLessonContainsLongInlineTokenWideFencedCodeBlock)
	ctx.When(`^a reader opens it at 375 pixels wide$`, world.StepReaderOpens375PixelsWide)
	ctx.Then(`^inline code wraps within the article$`, world.StepInlineCodeWrapsWithinArticle)
	ctx.Step(`^the fenced block scrolls internally without widening the document$`, world.StepFencedBlockScrollsInternallyWithoutWideningDocum)
	ctx.When(`^a reader requests a nonexistent content route in a supported locale$`, world.StepReaderRequestsNonexistentContentRouteSupportedLo)
	ctx.Then(`^the response status is 404$`, world.StepResponseStatus404)
	ctx.Step(`^the reader sees a localized not-found page with usable navigation$`, world.StepReaderSeesLocalizedFoundPageUsableNavigation)
}
